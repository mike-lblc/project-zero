"""СОСТАВ АГЕНТОВ — роли, правила, инструменты, мера успеха.

Здесь каждый агент получает то, чего у него не было: системный промпт,
поимённый набор инструментов и KPI, по которому его работу можно признать
состоявшейся или нет.

ПРОМПТЫ НАПИСАНЫ ПО НАШЕЙ ЖЕ ИСТОРИИ. В каждом есть запрет, выведенный из
конкретной ошибки, которая уже случилась и стоила работы. Промпт из общих
слов («будь полезным, работай хорошо») не меняет поведения — он меняет только
самоощущение. Работает запрет с примером: «не считай отсутствие ответа
отсутствием работы, так мы потеряли обход рынка».

Инструменты — это ОБЁРТКИ над тем, что уже проверено в бою. Агент не получает
новых возможностей вместе с рассуждением; он получает право выбирать между
теми, что уже есть. Давать рассуждающему агенту непроверенные инструменты
значит умножать риск на скорость.
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
