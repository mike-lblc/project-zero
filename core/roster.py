@tool("browse_platform", "GREEN",
      "открыть площадку настоящим браузером и прочесть то, что рисуется скриптом",
      needs=("сеть", "браузер"))
def _browse():
    from core import browser
    from core.db import connect
    c = connect()
    try:
        row = c.execute("SELECT platform FROM money_paths WHERE open_to_us=1 "
                        "AND (evidence IS NULL OR evidence NOT LIKE '%браузер%') "
                        "ORDER BY score DESC LIMIT 1").fetchone()
    except Exception:
        row = None
    finally:
        c.close()
    if not row:
        return "площадок, не читанных браузером, нет"
    r = browser.probe("https://" + row[0])
    if not r.get("ok"):
        return f"{row[0]}: {r.get('why')}"
    return (f"{row[0]}: сумм на странице {r['amounts']}, ссылок {r['links']} "
            f"— обычный запрос этого не показывал" if r["amounts"] else
            f"{row[0]}: браузером тоже пусто — площадка не отдаёт задачи списком")


