@tool("recall_memory", "GREEN",
      "вспомнить по СМЫСЛУ, что система уже выясняла — включая выводы, "
      "сформулированные другими словами")
def _recall():
    from core import recall
    # Три действия, и порядок важен. Сначала знание (уроки, починки, стены),
    # потом свежие наблюдения, и только потом чистка: память, набитая дежурной
    # отчётностью, отвечает на вопрос «почему источник молчит» строкой про
    # зависшие задачи — механически исправно и по существу бесполезно.
    k = recall.index_knowledge()
    n = recall.index_existing(60)
    gone = recall.forget_routine()
    st = recall.stats()
    return (f"уроков добавлено {k}, наблюдений {n}, убрано отчётности {gone}; "
            f"всего в памяти {st['всего']}: {st['по видам']}")


